using System.Collections.Generic;
using System.Threading;
using System.Threading.Tasks;
using Resgrid.Model.Identity;
using Resgrid.Model.Onboarding;

namespace Resgrid.Model.Services
{
	/// <summary>
	/// Account operations behind ASP.NET Identity's UserManager, so services that create members run in any host (Web, API,
	/// the worker) without depending on the web stack. Registered wherever UserManager is.
	/// </summary>
	public interface IMemberAccountService
	{
		Task<IdentityUser> FindByIdAsync(string userId);

		Task<IdentityUser> FindByEmailAsync(string email);

		Task<IdentityUser> FindByNameAsync(string userName);

		/// <summary>Creates the account; with a null password the account has none and cannot sign in by password.</summary>
		Task<MemberAccountResult> CreateAsync(IdentityUser user, string password);

		Task<MemberAccountResult> SetEmailConfirmedAsync(IdentityUser user, bool confirmed);

		/// <summary>Deletes an account the import created (rollback, section 11.8). Never used for an account with other memberships.</summary>
		Task<MemberAccountResult> DeleteAsync(IdentityUser user);

		/// <summary>Sets the first password of an account created without one (an imported person accepting their invitation, 15.4).</summary>
		Task<MemberAccountResult> AddPasswordAsync(IdentityUser user, string password);
	}

	public sealed class MemberAccountResult
	{
		public bool Succeeded { get; set; }
		/// <summary>Value-free error codes from Identity ("DuplicateEmail", "InvalidUserName").</summary>
		public List<string> Errors { get; set; } = new List<string>();

		public static MemberAccountResult Ok() => new MemberAccountResult { Succeeded = true };
	}

	/// <summary>
	/// One idempotent way to create a member (wizard plan section 11.2): account (pre-generated id), profile, user role and
	/// extension info, membership, department-scoped sensitive data, group, roles and custom fields. Each sub-step is keyed by
	/// the target user id, so a retry after a crash finishes what is missing instead of creating a second person. Used by the
	/// importer with the import effect policy and by AddPerson and SCIM with the interactive one.
	/// </summary>
	public interface IMemberProvisioningService
	{
		Task<MemberProvisioningResult> ProvisionAsync(MemberProvisioningRequest request, ImportEffectPolicy effects, CancellationToken cancellationToken = default);

		/// <summary>A unique username derived from the email's local part, with a numeric suffix on collision (section 12.3).</summary>
		Task<string> GenerateUserNameAsync(string email);
	}

	public sealed class MemberProvisioningRequest
	{
		public int DepartmentId { get; set; }
		/// <summary>The account id; pre-generated by the importer so a retry finds the same account (section 11.3).</summary>
		public string UserId { get; set; }
		/// <summary>
		/// <see cref="UserId"/> was reserved for this provisioning alone (the importer's account claim, committed before the chunk
		/// transaction, section 11.3). The account is created outside that transaction, so one already under the id was made by
		/// an earlier attempt whose chunk rolled back or was replayed row by row: it counts as created here, and rollback may
		/// delete it.
		/// </summary>
		public bool UserIdReserved { get; set; }
		public string Email { get; set; }
		/// <summary>Null = generated from the email.</summary>
		public string UserName { get; set; }
		/// <summary>Null = no password (imported members set one when they accept their invitation).</summary>
		public string Password { get; set; }
		public bool EmailConfirmed { get; set; }
		/// <summary>Adds the user role and extension rows (AddPerson, import). SCIM never created them and keeps not doing so.</summary>
		public bool InitializeAccountExtras { get; set; } = true;
		public UserProfile Profile { get; set; }
		public bool IsAdmin { get; set; }
		public bool IsHidden { get; set; }
		public bool IsDisabled { get; set; }
		public bool MustChangePassword { get; set; }
		/// <summary><see cref="ImportActivationState"/> for an imported member (Dormant); null otherwise.</summary>
		public int? ImportActivationState { get; set; }
		/// <summary>Department-scoped member data, written through the ADP protection seam.</summary>
		public DepartmentMemberSensitiveData SensitiveData { get; set; }
		public int? GroupId { get; set; }
		public bool GroupAdmin { get; set; }
		public List<int> RoleIds { get; set; } = new List<int>();
		public List<UdfFieldValue> CustomFieldValues { get; set; } = new List<UdfFieldValue>();
		/// <summary>The administrator (or the authorizing administrator under managed migration) the writes are attributed to.</summary>
		public string ActingUserId { get; set; }
	}

	public sealed class MemberProvisioningResult
	{
		public bool Succeeded { get; set; }
		/// <summary>Stable code: account_exists_elsewhere, account_create_failed, role_requirements_unmet…</summary>
		public string ErrorCode { get; set; }
		public string UserId { get; set; }
		public string UserName { get; set; }
		/// <summary>
		/// True when the account exists because of this provisioning: this call created it, or an earlier attempt did under a
		/// reserved <see cref="MemberProvisioningRequest.UserId"/> (rollback may delete it, section 11.8).
		/// </summary>
		public bool CreatedAccount { get; set; }
		public DepartmentMember Member { get; set; }
		/// <summary>Roles that could not be assigned because certification enforcement blocked them.</summary>
		public List<int> BlockedRoleIds { get; set; } = new List<int>();
	}
}
