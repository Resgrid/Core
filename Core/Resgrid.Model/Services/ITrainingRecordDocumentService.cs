using System;
using System.Threading;
using System.Threading.Tasks;

namespace Resgrid.Model.Services
{
	/// <summary>
	/// Round 10 (Omni): a member's own transcript and certificate of completion as sealed PDFs, outside the web page (the v4 downloads). The
	/// documents are the web's (Training records → Transcript PDF and Certificate): the same lines, labels, verification code, QR and
	/// department template, sealed under the same subject revision, so either host's sealed copy is the one the other serves again. The
	/// caller checked the Trainings module; only the member's own records are printed.
	/// </summary>
	public interface ITrainingRecordDocumentService
	{
		/// <summary>The member's transcript (department-local dates, optional category and source filters); voided records left out.</summary>
		Task<TrainingRecordDocumentFile> GetMyTranscriptPdfAsync(TrainingRecordDocumentRequest request, DateTime? fromLocalDate, DateTime? toLocalDate, int? categoryId,
			int? source, CancellationToken cancellationToken = default);

		/// <summary>The certificate of one of the member's own verified records; null for anyone else's, an unverified or an unknown record.</summary>
		Task<TrainingRecordDocumentFile> GetMyCertificatePdfAsync(TrainingRecordDocumentRequest request, int learningRecordId, CancellationToken cancellationToken = default);
	}

	/// <summary>Who asks, in which language, and how a QR is drawn (the host renders it: the core has no image library).</summary>
	public sealed class TrainingRecordDocumentRequest
	{
		public int DepartmentId { get; set; }

		/// <summary>The member: the holder of the records and the one who asked.</summary>
		public string UserId { get; set; }

		/// <summary>The member's user name, printed as "generated by" when the department has no name for them.</summary>
		public string UserName { get; set; }

		/// <summary>The documents' language (a supported culture; English otherwise).</summary>
		public string Culture { get; set; }

		/// <summary>A data: URL (PNG) of a QR code for a URL; null leaves the LMS certificate without its QR image.</summary>
		public Func<string, string> QrDataUrl { get; set; }
	}

	/// <summary>A rendered document: sealed when <see cref="Sealed"/>, otherwise the unsealed PDF while sealing is pending (worker 90).</summary>
	public sealed class TrainingRecordDocumentFile
	{
		public byte[] Bytes { get; set; }
		public string FileName { get; set; }
		public string ContentType { get; set; } = "application/pdf";
		public bool Sealed { get; set; }
	}
}
