using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading.Tasks;
using Resgrid.Model;
using Resgrid.Model.Services;

namespace Resgrid.Services
{
	/// <summary>
	/// The personnel status table (moved out of HomeController.GetUserStatusTable unchanged, 2026-10-31) so the classic
	/// dashboard's partial and the personnel.board widget group, filter and sort people the same way.
	/// </summary>
	public class PersonnelStatusBoardService : IPersonnelStatusBoardService
	{
		/// <summary>The weight of a status the department gave no sort position (and of "no status").</summary>
		public const int UnweightedStatus = 9000;

		private readonly IDepartmentsService _departmentsService;
		private readonly IActionLogsService _actionLogsService;
		private readonly IDepartmentGroupsService _departmentGroupsService;
		private readonly ICustomStateService _customStateService;
		private readonly IDepartmentSettingsService _departmentSettingsService;
		private readonly IUserStateService _userStateService;
		private readonly IUsersService _usersService;
		private readonly IAuthorizationService _authorizationService;

		public PersonnelStatusBoardService(IDepartmentsService departmentsService, IActionLogsService actionLogsService,
			IDepartmentGroupsService departmentGroupsService, ICustomStateService customStateService, IDepartmentSettingsService departmentSettingsService,
			IUserStateService userStateService, IUsersService usersService, IAuthorizationService authorizationService)
		{
			_departmentsService = departmentsService;
			_actionLogsService = actionLogsService;
			_departmentGroupsService = departmentGroupsService;
			_customStateService = customStateService;
			_departmentSettingsService = departmentSettingsService;
			_userStateService = userStateService;
			_usersService = usersService;
			_authorizationService = authorizationService;
		}

		public async Task<PersonnelStatusBoard> GetBoardAsync(int departmentId, string viewerUserId)
		{
			var board = new PersonnelStatusBoard();
			board.Department = await _departmentsService.GetDepartmentByIdAsync(departmentId, false);
			board.LastUserActionlogs = await _actionLogsService.GetLastActionLogsForDepartmentAsync(departmentId);
			board.DepartmentGroups = await _departmentGroupsService.GetAllGroupsForDepartmentAsync(departmentId);
			board.Stations = await _departmentGroupsService.GetAllStationGroupsForDepartmentAsync(departmentId);
			board.UsersGroup = await _departmentGroupsService.GetGroupForUserAsync(viewerUserId, departmentId);
			board.States = await _customStateService.GetActivePersonnelStateForDepartmentAsync(departmentId);
			board.StaffingLevels = await _customStateService.GetActiveStaffingLevelsForDepartmentAsync(departmentId);
			board.DefaultStatus = await _customStateService.GetDefaultPersonnelStatusAsync(departmentId);

			var personnelSortOrder = await _departmentSettingsService.GetDepartmentPersonnelSortOrderAsync(departmentId);
			var personnelStatusSortOrder = await _departmentSettingsService.GetDepartmentPersonnelListStatusSortOrderAsync(departmentId);

			var userStates = await _userStateService.GetLatestStatesForDepartmentAsync(departmentId);
			var allUsers = await _usersService.GetUserGroupAndRolesByDepartmentIdInLimitAsync(departmentId, false, false, false);
			board.ExcludedUsers = await _departmentsService.GetAllDisabledOrHiddenUsersAsync(departmentId);

			List<string> groupedUserIds = new List<string>();

			foreach (var dg in board.DepartmentGroups)
			{
				var group = new PersonnelStatusBoardGroup();
				group.Group = dg;

				var membersToProcess = from member in dg.Members
									   where !(board.ExcludedUsers.Any(item2 => item2 == member.UserId))
									   select member;

				foreach (var u in membersToProcess)
				{
					if (!await _authorizationService.CanUserViewPersonViaMatrixAsync(u.UserId, viewerUserId, departmentId))
						continue;

					if (allUsers.Any(x => x.UserId == u.UserId))
					{
						groupedUserIds.Add(u.UserId);
						var userInfo = allUsers.FirstOrDefault(x => x.UserId == u.UserId);

						UserState state = userStates.FirstOrDefault(x => x.UserId == u.UserId);

						if (state == null)
							state = AutoGeneratedState(u.UserId);

						if (!board.DepartmentUserStates.ContainsKey(u.UserId))
							board.DepartmentUserStates.Add(u.UserId, state);

						var al = board.LastUserActionlogs.FirstOrDefault(x => x.UserId == u.UserId);

						group.Entries.Add(new PersonnelStatusBoardEntry
						{
							UserInfo = userInfo,
							CurrentStatus = al,
							CurrentStaffing = state,
							Weight = WeightOf(al, personnelStatusSortOrder)
						});
					}
				}

				group.Entries = Sort(group.Entries, personnelSortOrder);
				board.Groups.Add(group);
			}

			var ungroupedUsers = from u in allUsers
								 where !(groupedUserIds.Contains(u.UserId)) && !(board.ExcludedUsers.Any(item2 => item2 == u.UserId))
								 select u;

			var unGroupedUsersGroup = new PersonnelStatusBoardGroup();
			unGroupedUsersGroup.Group = null;
			foreach (var u in ungroupedUsers)
			{
				if (!await _authorizationService.CanUserViewPersonViaMatrixAsync(u.UserId, viewerUserId, departmentId))
					continue;

				board.UnGroupedUsers.Add(u.UserId);

				UserState state = userStates.FirstOrDefault(x => x.UserId == u.UserId);
				var userInfo = allUsers.FirstOrDefault(x => x.UserId == u.UserId);

				if (state == null)
					state = AutoGeneratedState(u.UserId);

				var al = board.LastUserActionlogs.FirstOrDefault(x => x.UserId == u.UserId);

				unGroupedUsersGroup.Entries.Add(new PersonnelStatusBoardEntry
				{
					UserInfo = userInfo,
					CurrentStatus = al,
					CurrentStaffing = state,
					Weight = WeightOf(al, personnelStatusSortOrder)
				});
			}

			unGroupedUsersGroup.Entries = Sort(unGroupedUsersGroup.Entries, personnelSortOrder);
			board.Groups.Add(unGroupedUsersGroup);

			return board;
		}

		private static UserState AutoGeneratedState(string userId)
		{
			var state = new UserState();
			state.UserId = userId;
			state.AutoGenerated = true;
			state.Timestamp = DateTime.UtcNow;
			state.State = (int)UserStateTypes.Available;

			return state;
		}

		private static int WeightOf(ActionLog al, List<PersonnelListStatusOrder> personnelStatusSortOrder)
		{
			if (al == null)
				return UnweightedStatus;

			if (personnelStatusSortOrder != null && personnelStatusSortOrder.Any())
			{
				var statusSorting = personnelStatusSortOrder.FirstOrDefault(x => x.StatusId == al.ActionTypeId);
				if (statusSorting != null)
					return statusSorting.Weight;
			}

			return UnweightedStatus;
		}

		private static List<PersonnelStatusBoardEntry> Sort(List<PersonnelStatusBoardEntry> entries, PersonnelSortOrders personnelSortOrder)
		{
			switch (personnelSortOrder)
			{
				case PersonnelSortOrders.FirstName:
					return entries.OrderBy(x => x.Weight).ThenBy(x => x.UserInfo.FirstName).ToList();
				case PersonnelSortOrders.LastName:
					return entries.OrderBy(x => x.Weight).ThenBy(x => x.UserInfo.LastName).ToList();
				default:
					// PersonnelSortOrders.Default and anything unknown.
					return entries.OrderBy(x => x.Weight).ToList();
			}
		}
	}
}
