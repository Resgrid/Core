		[Test]
		public async Task My_status_offers_the_classic_built_in_buttons_and_never_echoes_the_staffing_note()
		{
			var customStates = CustomStateService();
			var lastState = new UserState { UserStateId = 12, UserId = Viewer, DepartmentId = Dept, State = (int)UserStateTypes.Delayed, Timestamp = Now.AddMinutes(-9), Note = "secret staffing note" };
			var lastStatus = new ActionLog { UserId = Viewer, DepartmentId = Dept, ActionTypeId = (int)ActionTypes.RespondingToStation, DestinationId = 30, Timestamp = Now.AddMinutes(-2) };

			var data = (PersonnelMyStatusWidgetData)await MyStatusProvider(customStates, lastStatus, lastState, active: new List<Call> { Call(1), Call(2) })
				.GetDataAsync(Context("personnel.myStatus"), CancellationToken.None);

			data.CustomStatuses.Should().BeFalse();
			data.Statuses.Select(s => s.Id).Should().Equal(2, 1, 0, 4, 3);
			data.Statuses[0].DetailType.Should().Be((int)CustomStateDetailTypes.CallsAndStations, "Responding carries the respond-to menu");
			data.Statuses[0].Chip.Color.Should().Be("#449d44");
			data.StaffingLevels.Select(s => s.Id).Should().Equal(0, 1, 2, 3, 4);
			data.CurrentStatus.Id.Should().Be((int)ActionTypes.RespondingToStation);
			data.CurrentStatusDestination.Should().Be("Station 3");
			data.CurrentStaffing.Text.Should().Be("Delayed");
			data.Stations.Select(s => s.Name).Should().Equal("Station 3");
			data.Calls.Select(c => c.Id).Should().Equal(1, 2);
			data.SetStatus.Url.Should().Be("/User/Home/SetCustomAction");
			data.SetStaffingWithNote.Body.Should().Be("form", "a note never travels in the URL");
			JsonSerializer.Serialize(data).Should().NotContain("secret staffing note");
		}

		[Test]
		public async Task My_status_uses_the_departments_own_statuses_and_ignores_another_departments_rows()
		{
			var customStates = CustomStateService(
				CustomStates(CustomStateTypes.Personnel, Detail(CustomOnScene, "At Hall", "#112233", (int)ActionBaseTypes.InQuarters, order: 1)),
				CustomStates(CustomStateTypes.Staffing, Detail(CustomStaffingOff, "Off", "#445566", (int)StaffingBaseTypes.OffDuty)));
			customStates.Setup(s => s.GetActivePersonnelStateForDepartmentAsync(Dept)).ReturnsAsync(CustomStates(CustomStateTypes.Personnel,
				Detail(CustomOnScene, "At Hall", "#112233", (int)ActionBaseTypes.InQuarters, order: 1)));
			customStates.Setup(s => s.GetActiveStaffingLevelsForDepartmentAsync(Dept)).ReturnsAsync(CustomStates(CustomStateTypes.Staffing,
				Detail(CustomStaffingOff, "Off", "#445566", (int)StaffingBaseTypes.OffDuty)));

			var foreignStatus = new ActionLog { UserId = Viewer, DepartmentId = OtherDept, ActionTypeId = 2, Timestamp = Now };
			var autoGenerated = new UserState { UserId = Viewer, State = 0, AutoGenerated = true, Timestamp = Now };

			var data = (PersonnelMyStatusWidgetData)await MyStatusProvider(customStates, foreignStatus, autoGenerated)
				.GetDataAsync(Context("personnel.myStatus"), CancellationToken.None);

			data.CustomStatuses.Should().BeTrue();
			data.Statuses.Single().Chip.Should().BeEquivalentTo(new { Id = CustomOnScene, Text = "At Hall", Color = "#112233", IsCustom = true }, o => o.ExcludingMissingMembers());
			data.StaffingLevels.Single().Chip.Availability.Should().Be((int)AvailabilityClass.Unavailable);
			data.CurrentStatus.Should().BeNull("a status from another department is not the viewer's here");
			data.CurrentStaffing.Should().BeNull("an auto-generated Available is not a real staffing row");
		}

