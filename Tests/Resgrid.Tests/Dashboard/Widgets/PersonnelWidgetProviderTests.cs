		[Test]
		public async Task Status_summary_counts_visible_active_members_with_the_default_for_no_status()
		{
			var (users, departments) = Roster();
			var logs = new Mock<IActionLogsService>();
			logs.Setup(l => l.GetLastActionLogsForDepartmentAsync(Dept, false, false, false)).ReturnsAsync(new List<ActionLog>
			{
				new ActionLog { ActionLogId = 1, UserId = "u1", DepartmentId = Dept, ActionTypeId = (int)ActionTypes.Responding },
				new ActionLog { ActionLogId = 2, UserId = "u2", DepartmentId = Dept, ActionTypeId = (int)ActionTypes.OnScene },
				new ActionLog { ActionLogId = 3, UserId = "matrix", DepartmentId = Dept, ActionTypeId = (int)ActionTypes.NotResponding }
			});
			var customStates = CustomStateService();
			customStates.Setup(c => c.GetDefaultPersonnelStatusAsync(Dept)).ReturnsAsync(new CustomStateDetail { CustomStateDetailId = 0, ButtonText = "Standing By" });

			var provider = new PersonnelStatusSummaryWidgetProvider(logs.Object, users.Object, departments.Object, Matrix(hiddenPeople: new[] { "matrix" }).Object, customStates.Object);
			var data = (PersonnelStatusSummaryWidgetData)await provider.GetDataAsync(Context("personnel.statusSummary"), CancellationToken.None);

			data.Total.Should().Be(4, "hidden members and people outside the viewer's matrix are not counted");
			data.Committed.Should().Be(2);
			data.Available.Should().Be(2, "no status reads as Standing By");
			data.Unavailable.Should().Be(0);
			data.ByStatus.First().Status.Id.Should().Be((int)ActionTypes.StandingBy);
		}

		[Test]
		public async Task Staffing_summary_counts_levels_per_group_and_visible_people_on_duty()
		{
			var (users, departments) = Roster();
			var states = new Mock<IUserStateService>();
			states.Setup(s => s.GetLatestStatesForDepartmentAsync(Dept, false)).ReturnsAsync(new List<UserState>
			{
				new UserState { UserId = "u1", State = (int)UserStateTypes.Unavailable, Timestamp = Now },
				new UserState { UserId = "u3", State = (int)UserStateTypes.OnShift, Timestamp = Now }
			});
			var groups = new Mock<IDepartmentGroupsService>();
			groups.Setup(g => g.GetAllGroupsForDepartmentAsync(Dept)).ReturnsAsync(new List<DepartmentGroup> { Group(1, "Alpha"), Group(2, "Bravo") });
			var shifts = new Mock<IShiftsService>();
			shifts.Setup(s => s.GetOnDutyUserIdsForGroupsAsync(Dept, It.IsAny<IEnumerable<int>>(), Now)).ReturnsAsync(new Dictionary<int, List<string>>
			{
				[1] = new List<string> { "u1", "hidden" },
				[2] = new List<string>()
			});

			var provider = new PersonnelStaffingSummaryWidgetProvider(states.Object, users.Object, departments.Object, Matrix(hiddenPeople: new[] { "matrix" }).Object,
				CustomStateService().Object, groups.Object, shifts.Object);
			var data = (PersonnelStaffingSummaryWidgetData)await provider.GetDataAsync(Context("personnel.staffingSummary"), CancellationToken.None);

			data.Total.Should().Be(4);
			data.AvailableCount.Should().Be(3, "Available (no row) and On Shift count; Unavailable does not");
			data.OnDutyCount.Should().Be(1, "a hidden member on the roster is not counted");
			data.ByGroup.Select(g => (g.Name, g.Total, g.AvailableCount, g.OnDutyCount)).Should().Equal(("Alpha", 2, 1, (int?)1), ("Bravo", 1, 1, (int?)null));
		}

