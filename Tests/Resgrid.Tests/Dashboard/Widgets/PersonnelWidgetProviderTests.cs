		private static PersonnelStatusBoard Board(params PersonnelStatusBoardGroup[] groups)
		{
			return new PersonnelStatusBoard
			{
				DepartmentGroups = groups.Where(g => g.Group != null).Select(g => g.Group).ToList(),
				Stations = new List<DepartmentGroup> { Group(30, "Station 3", type: (int)DepartmentGroupTypes.Station) },
				Groups = groups.ToList(),
				DefaultStatus = new CustomStateDetail { CustomStateDetailId = 0, ButtonText = "Standing By" }
			};
		}

		private static PersonnelStatusBoardEntry Entry(string userId, string name, ActionLog status = null, UserState staffing = null)
		{
			return new PersonnelStatusBoardEntry
			{
				UserInfo = Member(userId, name, "Last"),
				CurrentStatus = status,
				CurrentStaffing = staffing ?? new UserState { UserId = userId, State = 0, AutoGenerated = true, Timestamp = Now },
				Weight = 9000
			};
		}

		private static PersonnelBoardWidgetProvider BoardProvider(PersonnelStatusBoard board, Mock<IProtectedReadService> reads)
		{
			var boards = new Mock<IPersonnelStatusBoardService>(MockBehavior.Strict);
			boards.Setup(b => b.GetBoardAsync(Dept, Viewer)).ReturnsAsync(board);
			return new PersonnelBoardWidgetProvider(boards.Object, CustomStateService().Object, reads.Object);
		}

		private static Mock<IProtectedReadService> RedactingUserStates()
		{
			var reads = new Mock<IProtectedReadService>(MockBehavior.Strict);
			reads.Setup(r => r.ResolveUserStatesForReadAsync(Dept, It.IsAny<IReadOnlyList<UserState>>(), It.IsAny<string>(), Viewer, It.IsAny<CancellationToken>()))
				.Returns((int d, IReadOnlyList<UserState> states, string grant, string user, CancellationToken t) =>
				{
					var result = new ProtectedReadResult { IsProtected = true };
					foreach (var state in states.Where(s => ProtectedDataEnvelope.HasEnvelopePrefix(s.Note)))
					{
						state.Note = grant == "good" ? "Sick kid" : ProtectedDataEnvelope.RedactionValue;
						if (grant != "good" && !result.RedactedFields.Contains("userstates.note"))
							result.RedactedFields.Add("userstates.note");
					}
					return Task.FromResult(result);
				});
			return reads;
		}

		[Test]
		public async Task Board_mirrors_the_shared_status_table_and_protects_staffing_notes()
		{
			var parent = Group(1, "Operations", members: new DepartmentGroupMember { UserId = Viewer, IsAdmin = true });
			var child = Group(2, "Station 3 crew", parent: 1);
			var grandchild = Group(3, "Rescue team", parent: 2);
			var board = Board(
				new PersonnelStatusBoardGroup { Group = parent, Entries = { Entry("u1", "Alex",
					new ActionLog { ActionTypeId = (int)ActionTypes.RespondingToStation, DestinationId = 30, Timestamp = Now.AddMinutes(-1) },
					new UserState { UserStateId = 7, UserId = "u1", State = 2, Timestamp = Now.AddMinutes(-3), Note = "rgdp:1:2:BBBB" }) } },
				new PersonnelStatusBoardGroup { Group = grandchild, Entries = { Entry("u3", "Casey") } },
				new PersonnelStatusBoardGroup { Group = child, Entries = { Entry("u2", "Blake",
					staffing: new UserState { UserStateId = 8, UserId = "u2", State = 3, Timestamp = Now, Note = "Covering E2" }) } },
				new PersonnelStatusBoardGroup { Group = null, Entries = { Entry("u4", "Drew") } });

			var viewer = ViewerWith("Department_View");
			viewer.AdpEnforced = true;
			var data = (PersonnelBoardWidgetData)await BoardProvider(board, RedactingUserStates()).GetDataAsync(Context("personnel.board", viewer), CancellationToken.None);

			data.Groups.Select(g => g.GroupId).Should().Equal(new int?[] { 1, 2, 3, null }, "children follow their parent at any depth, ungrouped last");
			data.TotalCount.Should().Be(4);

			var alex = data.Groups[0].People.Single();
			alex.Status.Id.Should().Be((int)ActionTypes.RespondingToStation);
			alex.StatusDestination.Should().Be("Station 3");
			alex.Staffing.Text.Should().Be("Unavailable");
			alex.StaffingNote.IsProtected.Should().BeTrue();
			alex.StaffingNote.CanReveal.Should().BeFalse("the viewer holds no ADP view permission");
			alex.StaffingNote.Value.Should().BeNull();
			alex.CanEdit.Should().BeTrue("the viewer administers this group");
			data.Groups[0].CanReset.Should().BeTrue("group admin, built-in statuses");

			data.Groups[1].People.Single().StaffingNote.Should().BeEquivalentTo(DashboardProtectedText.Plain("Covering E2"));
			data.Groups[1].People.Single().CanEdit.Should().BeFalse();
			data.Groups[2].People.Single().Status.Text.Should().Be("Standing By", "no status inside the window shows the department's default");
			data.Groups[2].People.Single().StaffingNote.Should().BeNull();
			data.Groups[2].People.Single().StaffingOnUtc.Should().BeNull();
			data.CanResetAll.Should().BeFalse();
			data.ResetAll.Should().BeNull();
		}

		[Test]
		public async Task Board_filters_groups_by_department_ids_and_hides_unavailable()
		{
			var g1 = Group(1, "A");
			var g2 = Group(2, "B");
			var board = Board(
				new PersonnelStatusBoardGroup { Group = g1, Entries = { Entry("u1", "Alex", staffing: new UserState { UserStateId = 1, UserId = "u1", State = 2, Timestamp = Now }), Entry("u2", "Blake") } },
				new PersonnelStatusBoardGroup { Group = g2, Entries = { Entry("u3", "Casey") } },
				new PersonnelStatusBoardGroup { Group = null, Entries = { Entry("u4", "Drew") } });

			var data = (PersonnelBoardWidgetData)await BoardProvider(board, new Mock<IProtectedReadService>(MockBehavior.Strict))
				.GetDataAsync(Context("personnel.board", settings: new Dictionary<string, object> { ["groups"] = new[] { "1", "404" }, ["hideUnavailable"] = true }), CancellationToken.None);

			data.Groups.Select(g => g.GroupId).Should().Equal(1);
			data.Groups.Single().People.Select(p => p.UserId).Should().Equal("u2");
			data.GroupFilterIgnored.Should().BeTrue("one of the requested groups is not the department's");

			var foreignOnly = (PersonnelBoardWidgetData)await BoardProvider(board, new Mock<IProtectedReadService>(MockBehavior.Strict))
				.GetDataAsync(Context("personnel.board", settings: new Dictionary<string, object> { ["groups"] = new[] { "404" }, ["sort"] = "name" }), CancellationToken.None);
			foreignOnly.Groups.Should().HaveCount(3, "a filter naming no department group is ignored");
		}

