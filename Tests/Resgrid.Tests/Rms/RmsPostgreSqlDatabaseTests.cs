			list.Setup(l => l.RetrieveQueryList()).Returns(queries); return new Resgrid.Repositories.DataRepository.Queries.QueryFactory(list.Object);
		}

		private async Task<string> SeedOperational()
		{
			var id = Guid.NewGuid().ToString(); var old = DateTime.UtcNow.AddYears(-10);
