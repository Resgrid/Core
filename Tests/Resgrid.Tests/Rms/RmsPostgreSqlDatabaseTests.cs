			if (string.IsNullOrWhiteSpace(_master)) Assert.Ignore("Set RESGRID_RMS_POSTGRES_TEST_CONNECTION to an isolated PostgreSQL test server.");
			_previousType = DataConfig.DatabaseType; DataConfig.DatabaseType = DatabaseTypes.Postgres;
			_database = "rms_verification_" + Guid.NewGuid().ToString("N");
			await using var master = new NpgsqlConnection(_master);
			await master.ExecuteAsync($"CREATE DATABASE {_database}");
			_connection = new NpgsqlConnectionStringBuilder(_master) { Database = _database }.ConnectionString;
			await using (var db = new NpgsqlConnection(_connection))
				await db.ExecuteAsync(@"CREATE EXTENSION citext;
CREATE TABLE departments (departmentid integer PRIMARY KEY); INSERT INTO departments VALUES (11),(12);
CREATE TABLE departmentsettings (departmentsettingid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,departmentid integer NOT NULL,settingtype integer NOT NULL,setting text NOT NULL);
CREATE TABLE workflowruns (workflowrunid citext PRIMARY KEY,workflowid citext NOT NULL,departmentid integer NOT NULL,status integer NOT NULL,completedon timestamp,inputpayload text,errormessage text);
CREATE TABLE workflowrunlogs (workflowrunlogid citext PRIMARY KEY,workflowrunid citext NOT NULL,renderedoutput text,actionresult text,errormessage text);");
			var versions = new HashSet<long> { 48, 49, 124, 142, 143, 144, 145, 150, 151, 153, 154, 155, 156, 157, 160, 164, 165, 166, 167, 168, 169, 170, 171, 173 };
			var migrations = typeof(M0150_AddRmsRecordsCorePg).Assembly.GetTypes().Where(t => typeof(IMigration).IsAssignableFrom(t) && !t.IsAbstract)
				.Where(t => t.GetCustomAttributes(typeof(MigrationAttribute), false).Cast<MigrationAttribute>().Any(a => versions.Contains(a.Version)))
				.Select(t => (IMigration)Activator.CreateInstance(t)).ToList();
			migrations.Should().HaveCount(versions.Count, "every selected shipped migration must be exercised");
			var source = new Mock<IMigrationSource>(); source.Setup(s => s.GetMigrations()).Returns(migrations);
			using var services = new ServiceCollection().AddFluentMigratorCore().ConfigureRunner(r => r.AddPostgres().WithGlobalConnectionString(_connection)).AddSingleton(source.Object).BuildServiceProvider();
			services.GetRequiredService<IMigrationRunner>().MigrateUp();
			TestContext.Progress.WriteLine("Migrated isolated PostgreSQL database: " + _database);
		}

		[OneTimeTearDown]
		public async Task RemoveOnlyTheDatabaseCreatedByThisFixture()
		{
			if (_database == null) return;
			DataConfig.DatabaseType = _previousType;
			if (!_database.StartsWith("rms_verification_", StringComparison.Ordinal) || _database.Length != 49 || !Guid.TryParseExact(_database.Substring(17), "N", out _)) throw new InvalidOperationException("Unexpected PostgreSQL test database name.");
			NpgsqlConnection.ClearAllPools();
			await using var master = new NpgsqlConnection(_master);
			await master.ExecuteAsync($"DROP DATABASE {_database} WITH (FORCE)");
		}

