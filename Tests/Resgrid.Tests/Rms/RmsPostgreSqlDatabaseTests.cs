			}, CancellationToken.None, true);
			return id;
		}

		[Test]
		public async Task Purge_erases_revisions_and_attachment_bytes_then_acknowledges_the_exact_purge()
		{
			var id = await SeedOperational(); var connections = Connections(); using var unit = new UnitOfWork(connections);
			var revision = Guid.NewGuid().ToString(); var attachment = Guid.NewGuid().ToString();
			await new RmsRevisionsRepository(connections, new PostgreSqlConfiguration(), unit, WriteQueries()).InsertAsync(new RmsRevision { RmsRevisionId = revision, DepartmentId = 11, ProtectionId = revision, RecordId = id, RecordKind = (int)RmsRecordKind.Operational, RevisionNumber = 1, DefinitionKey = RmsDefinitionKeys.Training, DefinitionVersion = 1, SnapshotJson = "{\"sensitive\":\"old report\"}", Checksum = new string('a', 64), ActorUserId = "officer", CreatedOn = DateTime.UtcNow.AddYears(-10) }, CancellationToken.None, true);
			await new RmsRecordAttachmentsRepository(connections, new PostgreSqlConfiguration(), unit, WriteQueries()).InsertAsync(new RmsRecordAttachment { RmsRecordAttachmentId = attachment, DepartmentId = 11, ProtectionId = attachment, RecordId = id, FileName = "scene.txt", ContentType = "text/plain", Data = new byte[] { 1, 2, 3 }, ByteSize = 3, Checksum = new string('b', 64), UploadedByUserId = "officer", UploadedOn = DateTime.UtcNow.AddYears(-10), CreatedOn = DateTime.UtcNow.AddYears(-10), ModifiedOn = DateTime.UtcNow.AddYears(-10), ScanState = (int)RmsAttachmentScanState.Clean, RowVersion = 1 }, CancellationToken.None, true);
			var repository = new RmsRetentionRepository(connections, new PostgreSqlConfiguration(), unit, WriteQueries());
			var result = await repository.PurgeAsync(11, id, RmsRecordKind.Operational, 1, DateTime.UtcNow);
			result.Purged.Should().BeTrue(result.Reason); result.SearchErasurePending.Should().BeTrue();
			await using var db = new NpgsqlConnection(_connection);
			(await db.ExecuteScalarAsync<string>("SELECT snapshotjson FROM rmsrevisions WHERE rmsrevisionid=@Id", new { Id = revision })).Should().Be("{}");
			(await db.ExecuteScalarAsync<int>("SELECT count(*) FROM rmsrecordattachments WHERE recordid=@Id", new { Id = id })).Should().Be(0);
			var target = (await repository.GetPendingSearchErasuresAsync(100)).Single(t => t.RecordId == id);
			(await repository.CompleteSearchErasureAsync(target, DateTime.UtcNow)).Should().BeTrue();
			(await repository.CompleteSearchErasureAsync(target, DateTime.UtcNow)).Should().BeFalse();
			Func<Task> late = () => new RmsRevisionsRepository(connections, new PostgreSqlConfiguration(), unit, WriteQueries()).InsertAsync(new RmsRevision { RecordId = id, DepartmentId = 11 }, CancellationToken.None, true);
			await late.Should().ThrowAsync<InvalidOperationException>();
		}

		[Test]
		public async Task Concurrent_command_reservations_have_one_owner_and_survive_a_new_connection()
		{
			var id = await SeedOperational(); var key = new string('c', 64); var checksum = new string('d', 64); var connections = Connections();
			using var firstUnit = new UnitOfWork(connections); using var secondUnit = new UnitOfWork(connections);
			var first = new RmsCommandReceiptsRepository(connections, new PostgreSqlConfiguration(), firstUnit, WriteQueries());
			var second = new RmsCommandReceiptsRepository(connections, new PostgreSqlConfiguration(), secondUnit, WriteQueries());
			var owner1 = Guid.NewGuid().ToString(); var owner2 = Guid.NewGuid().ToString();
			var outcomes = await Task.WhenAll(first.ReserveAsync(11, key, id, checksum, owner1), second.ReserveAsync(11, key, id, checksum, owner2));
			outcomes.Count(won => won).Should().Be(1);
			(await second.GetAsync(11, key)).IsPending.Should().BeTrue();
			(await first.CompleteAsync(12, key, id, checksum, outcomes[0] ? owner1 : owner2)).Should().BeFalse();
			(await second.CompleteAsync(11, key, id, checksum, outcomes[0] ? owner2 : owner1)).Should().BeFalse();
			(await second.CompleteAsync(11, key, id, checksum, outcomes[0] ? owner1 : owner2)).Should().BeTrue();
			(await first.GetAsync(11, key)).IsPending.Should().BeFalse();
		}

		[Test]
		public async Task Expired_shares_do_not_grant_scope_or_counts()
		{
			var id = await SeedOperational(); var share = Guid.NewGuid().ToString(); var connections = Connections(); using var unit = new UnitOfWork(connections);
			await using var db = new NpgsqlConnection(_connection);
			await db.ExecuteAsync("INSERT INTO rmsrecordgroupscopes (departmentid,recordid,departmentgroupid,anchortype,createdon) VALUES (11,@Id,808,@Anchor,now()); INSERT INTO rmsrecordshares (rmsrecordshareid,departmentid,protectionid,recordid,departmentgroupid,grantedbyuserid,grantedon,createdon,modifiedon) VALUES (@Share,11,@Share,@Id,808,'officer',now(),now(),now())", new { Id = id, Share = share, Anchor = (int)RmsGroupScopeAnchorType.Share });
			var scopes = new RmsRecordGroupScopesRepository(connections, new PostgreSqlConfiguration(), unit, WriteQueries());
			var records = new RmsOperationalRecordsRepository(connections, new PostgreSqlConfiguration(), unit, WriteQueries());
			(await scopes.GetForRecordAsync(11, id)).Should().ContainSingle();
			(await records.CountVisibleAsync(11, new[] { (int)RmsRecordState.Finalized }, new List<int> { 808 }, "reader")).Should().Be(1);
			await db.ExecuteAsync("UPDATE rmsrecordshares SET expireson=now()-interval '1 second' WHERE rmsrecordshareid=@Share", new { Share = share });
			(await scopes.GetForRecordsAsync(11, new[] { id })).Should().BeEmpty();
			(await scopes.GetEffectiveSharesAsync(11, new[] { 808 })).Should().BeEmpty();
			(await records.CountVisibleAsync(11, new[] { (int)RmsRecordState.Finalized }, new List<int> { 808 }, "reader")).Should().Be(0);
		}

		[Test]
		public async Task Precise_projection_paging_does_not_repeat_the_cursor_row()
		{
			var first = Guid.NewGuid().ToString(); var second = Guid.NewGuid().ToString(); var ids = new[] { first, second }.OrderBy(s => s, StringComparer.Ordinal).ToArray();
			await using var db = new NpgsqlConnection(_connection);
			foreach (var id in ids) await db.ExecuteAsync("INSERT INTO rmsrecordsearchprojections (rmsrecordsearchprojectionid,departmentid,protectionid,sourcetype,sourceid,definitionkey,state,recordcreatedon,createdon,modifiedon,rowversion) VALUES (@Id,11,@Id,1,@Id,'system.training',4,now(),now(),timestamp '2050-01-01 12:34:56.123456',1)", new { Id = id });
			var connections = Connections(); using var unit = new UnitOfWork(connections);
			var repository = new RmsRecordSearchProjectionsRepository(connections, new PostgreSqlConfiguration(), unit, WriteQueries());
			var page = (await repository.GetModifiedSinceAsync(11, new DateTime(2050, 1, 1, 0, 0, 0, DateTimeKind.Utc), 1)).Single();
			page.RmsRecordSearchProjectionId.Should().Be(ids[0]);
			var next = (await repository.GetModifiedSinceAsync(11, page.ModifiedOn, 1, page.RmsRecordSearchProjectionId)).Single();
			next.RmsRecordSearchProjectionId.Should().Be(ids[1]);
			(await repository.GetModifiedSinceAsync(11, next.ModifiedOn, 1, next.RmsRecordSearchProjectionId)).Should().BeEmpty();
		}
