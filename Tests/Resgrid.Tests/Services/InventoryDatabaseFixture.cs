		[OneTimeTearDown]
		public async Task RemoveOnlyThisFixturesDatabase()
		{
			_runner?.Dispose(); if (_configured) DataConfig.DatabaseType = _previous;
			if (!_created) return;
			if (!_database.StartsWith(DatabasePrefix, StringComparison.Ordinal) || !Guid.TryParseExact(_database.Substring(DatabasePrefix.Length), "N", out _)) throw new InvalidOperationException("Unexpected inventory fixture database name.");
			if (_type == DatabaseTypes.Postgres) NpgsqlConnection.ClearAllPools(); else SqlConnection.ClearAllPools();
			await using var master = Connect(_master);
			await master.ExecuteAsync(_type == DatabaseTypes.Postgres ? "DROP DATABASE " + _database + " WITH (FORCE)"
				: "ALTER DATABASE " + _database + " SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE " + _database);
		}

		private async Task WriteAsync(Func<InventoryStore, Task> work, int department = 77)
		{
			using var uow = new UnitOfWork(Connections()); var store = Store(uow);
			await uow.CreateOrGetConnectionAsync(); await store.LockDepartmentAsync(department);
			try { await work(store); uow.CommitChanges(); } catch { uow.DiscardChanges(); throw; }
		}
		private async Task RejectAsync(Func<InventoryStore, Task> work)
		{
			using var uow = new UnitOfWork(Connections()); var store = Store(uow);
			await uow.CreateOrGetConnectionAsync(); await store.LockDepartmentAsync(77);
			try { await FluentActions.Awaiting(() => work(store)).Should().ThrowAsync<DbException>(); } finally { uow.DiscardChanges(); }
		}
