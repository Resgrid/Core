		private async Task<Dictionary<string, string>> CleanupSnapshotAsync(DbConnection db, int? department = null)
		{
			var snapshot = new Dictionary<string, string>();
			foreach (var table in InventoryTables.All.Values.Concat(new[] { "WorkflowRuns", "WorkflowRunLogs", "DomainEventOutbox", "AuditLogs", "RmsRecordLegalHolds", "Inventories", "InventoryTypes", "Contacts" }))
			{
				var scope = !department.HasValue ? "" : table == "WorkflowRunLogs"
					? $" WHERE {Q("WorkflowRunId")} IN (SELECT {Q("WorkflowRunId")} FROM {Q("WorkflowRuns")} WHERE {Q("DepartmentId")}=@department)"
					: $" WHERE {Q("DepartmentId")}=@department";
				snapshot[table] = JsonConvert.SerializeObject(await db.QueryAsync($"SELECT * FROM {Q(table)}{scope} ORDER BY 1,2", new { department }));
			}
			return snapshot;
		}
