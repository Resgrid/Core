		private static InventoryPurchaseOrderItem PurchaseLine(InventoryPurchaseOrder order, InventoryItem item, int lineNumber = 1)
		{
			var row = NewRow<InventoryPurchaseOrderItem>(order.DepartmentId); row.PurchaseOrderId = order.Id; row.ItemId = item.Id;
			row.LineNumber = lineNumber; row.QuantityOrdered = 3.123456m; return row;
		}
		private static InventoryTransaction Receipt(InventoryPurchaseOrder order, InventoryPurchaseOrderItem line, InventoryItem item, InventoryLocation location, decimal quantity = 0.123456m)
		{
			var row = Posting(item, null, location, quantity); row.ReferenceType = (int)InventoryReferenceType.PurchaseOrder;
			row.ReferenceId = order.Id; row.PurchaseOrderItemId = line.Id; return row;
		}
		private static InventoryTransaction Posting(InventoryItem item, InventoryLocation from, InventoryLocation to, decimal quantity, InventoryTransactionType type = InventoryTransactionType.Receive)
		{
			var row = NewRow<InventoryTransaction>(item.DepartmentId); row.ItemId = item.Id; row.FromLocationId = from?.Id; row.ToLocationId = to?.Id;
			row.Quantity = quantity; row.TransactionType = (int)type; row.OccurredOn = DateTime.UtcNow; return row;
		}
		private static RecordInventoryUsage Usage(InventoryTransaction transaction, string sourceId = null)
		{
			var row = NewRow<RecordInventoryUsage>(transaction.DepartmentId);
			row.SourceType = (int)InventoryUsageSourceType.RmsRecord; row.SourceId = sourceId ?? Guid.NewGuid().ToString("D");
			row.RecordKind = (int)RmsRecordKind.Operational; row.ItemId = transaction.ItemId; row.AssetId = transaction.AssetId; row.LotId = transaction.LotId;
			row.SourceLocationId = transaction.FromLocationId ?? transaction.ToLocationId; row.Quantity = transaction.Quantity;
			row.TransactionId = transaction.Id; return row;
		}
