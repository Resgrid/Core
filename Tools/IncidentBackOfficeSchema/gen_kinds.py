import io, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from gen_web import gen_tables, UI

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
WEB = os.path.join(ROOT, 'Web', 'Resgrid.Web', 'Areas', 'User')
KINDS_OUT = os.path.join(WEB, 'Models', 'IncidentBackOffice', 'IncidentDeskKinds.Generated.cs')
CTRL_DIR = os.path.join(WEB, 'Controllers', 'IncidentBackOffice')

SECTION = {
    'IncidentBackOffice': 'Command', 'IncidentOperations': 'Command',
    'IncidentPeriods': 'Planning', 'IncidentOrganization': 'Planning', 'IncidentParticipants': 'Planning', 'IncidentCheckIn': 'Planning', 'IncidentDemob': 'Planning',
    'IncidentRequests': 'Logistics', 'IncidentFacilities': 'Logistics', 'IncidentLodging': 'Logistics', 'IncidentFeeding': 'Logistics', 'IncidentWater': 'Logistics',
    'IncidentServices': 'Logistics', 'IncidentGroundSupport': 'Logistics', 'IncidentCommunications': 'Logistics', 'IncidentVendors': 'Logistics',
    'IncidentProcurement': 'Finance', 'IncidentBudget': 'Finance', 'IncidentTime': 'Finance', 'IncidentCost': 'Finance', 'IncidentRecovery': 'Finance',
    'IncidentIntake': 'Finance', 'IncidentClaims': 'Finance',
    'IncidentIap': 'Records', 'IncidentCloseout': 'Records',
    'CoordinationBoards': 'Coordination', 'IncidentSituation': 'Coordination',
    'IncidentTeams': 'Department', 'IncidentPositions': 'Department', 'Vendors': 'Department', 'SupportPlan': 'Department', 'IncidentAuthority': 'Department',
}
BUSINESS = {'IncidentProcurement', 'IncidentBudget', 'IncidentTime', 'IncidentCost', 'IncidentRecovery', 'IncidentIntake', 'IncidentClaims', 'IncidentIap', 'IncidentCloseout'}
COORDINATION = {'CoordinationBoards', 'IncidentSituation'}
NO_ACTIVATION = {'IncidentBackOffice', 'CoordinationBoards', 'IncidentTeams', 'IncidentPositions', 'Vendors', 'SupportPlan', 'IncidentAuthority'}
# Desks with domain actions beyond the generic ledger: their controllers are hand-written (the aggregate is still generated).
HANDWRITTEN = {'IncidentBackOffice', 'IncidentPeriods', 'IncidentOrganization', 'IncidentParticipants', 'IncidentCheckIn', 'IncidentTeams', 'IncidentPositions'}


def groups():
    result = {}
    for t in gen_tables():
        result.setdefault(UI[t.table]['controller'], []).append(t)
    return result


def camel(name):
    return name[0].lower() + name[1:]


def gen_kinds(g):
    L = ['// <auto-generated>Generated from the Incident Back Office schema spec (large-incident-logistics-finance-plan.md §14.7). Regenerate, do not hand-edit.</auto-generated>',
         'using System.Collections.Generic;',
         'using Resgrid.Model.IncidentLogistics;',
         'using Resgrid.Model.Services;', '',
         'namespace Resgrid.Web.Areas.User.Models.IncidentBackOffice',
         '{',
         '\t/// <summary>The tables one desk hosts, built from their ledger services by constructor injection (registered per request in Startup).</summary>',
         '\tpublic interface IIncidentDeskKinds',
         '\t{',
         '\t\tIReadOnlyList<ILedgerKind> All { get; }',
         '\t}']
    for controller in sorted(g):
        tables = g[controller]
        L.append('')
        L.append('\tpublic sealed class %sLedgerKinds : IIncidentDeskKinds' % controller)
        L.append('\t{')
        params = ', '.join('IIncidentLedgerService<%s> %s' % (t.entity, camel(t.entity)) for t in tables)
        L.append('\t\tpublic %sLedgerKinds(%s)' % (controller, params))
        L.append('\t\t{')
        L.append('\t\t\tAll = new ILedgerKind[]')
        L.append('\t\t\t{')
        L.append(',\n'.join('\t\t\t\tIncidentLedgerCatalog.Kind(%s)' % camel(t.entity) for t in tables))
        L.append('\t\t\t};')
        L.append('\t\t}')
        L.append('')
        L.append('\t\tpublic IReadOnlyList<ILedgerKind> All { get; }')
        L.append('\t}')
    L.append('}')
    write(KINDS_OUT, L)


def gen_controller(controller):
    area = 'Business' if controller in BUSINESS else ('Coordination' if controller in COORDINATION else None)
    L = ['// <auto-generated>Generated from the Incident Back Office schema spec (large-incident-logistics-finance-plan.md §14.7). Regenerate, do not hand-edit;',
         '// a desk that needs domain actions moves to HANDWRITTEN in the generator and gets its own controller.</auto-generated>',
         'using System.Collections.Generic;',
         'using Resgrid.Web.Areas.User.Models.IncidentBackOffice;', '',
         'namespace Resgrid.Web.Areas.User.Controllers',
         '{',
         '\tpublic sealed class %sController : IncidentBackOfficeControllerBase' % controller,
         '\t{',
         '\t\tprivate readonly %sLedgerKinds _kinds;' % controller, '',
         '\t\tpublic %sController(IncidentDeskServices desk, %sLedgerKinds kinds) : base(desk)' % (controller, controller),
         '\t\t{',
         '\t\t\t_kinds = kinds;',
         '\t\t}', '',
         '\t\tprotected override string Section => "%s";' % SECTION[controller]]
    if area:
        L.append('\t\tprotected override IncidentBackOfficeArea ModuleArea => IncidentBackOfficeArea.%s;' % area)
    if controller in NO_ACTIVATION:
        L.append('\t\tprotected override bool RequiresActivation => false;')
    L.append('\t\tprotected override IReadOnlyList<ILedgerKind> Kinds => _kinds.All;')
    L.append('\t}')
    L.append('}')
    write(os.path.join(CTRL_DIR, '%sController.Generated.cs' % controller), L)


def write(path, lines):
    with io.open(path, 'w', encoding='utf-8', newline='') as f:
        f.write('\r\n'.join(lines) + '\r\n')


if __name__ == '__main__':
    g = groups()
    missing = [c for c in g if c not in SECTION]
    if missing:
        raise SystemExit('missing section: %s' % missing)
    gen_kinds(g)
    n = 0
    for controller in sorted(g):
        if controller not in HANDWRITTEN:
            gen_controller(controller)
            n += 1
    print('kinds', len(g), 'controllers', n)
