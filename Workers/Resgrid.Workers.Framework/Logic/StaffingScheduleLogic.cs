using Resgrid.Framework;
using Resgrid.Model;
using Resgrid.Model.Services;
using System;
using System.Threading.Tasks;
using Autofac;

namespace Resgrid.Workers.Framework.Logic
{
	public class StaffingScheduleLogic
	{
		public async Task<Tuple<bool, string>> Process(StaffingScheduleQueueItem item)
		{
			bool success = true;
			string result = "";

			if (item != null && item.ScheduledTask != null)
			{
				// Own scope per item: root-scope services would share the process-wide root unit of work.
				using var scope = Bootstrapper.GetKernel().BeginLifetimeScope();
				var userStateService = scope.Resolve<IUserStateService>();
				var departmentsService = scope.Resolve<IDepartmentsService>();
				var scheduledTasksService = scope.Resolve<IScheduledTasksService>();
				var customStateService = scope.Resolve<ICustomStateService>();

				// ADP department operation lock: staffing mutations are deferred, not dropped — the
				// occurrence is skipped WITHOUT a completion log so the scheduler re-picks it after
				// the lock releases (plan section 20.2).
				if (await DepartmentLockGuard.IsDepartmentLockedAsync(item.ScheduledTask.DepartmentId))
					return new Tuple<bool, string>(true, $"deferred: department {item.ScheduledTask.DepartmentId} is locked");

				try
				{
					if (item.ScheduledTask.TaskType == (int)TaskTypes.UserStaffingLevel)
					{
						await userStateService.CreateUserState(item.ScheduledTask.UserId, item.ScheduledTask.DepartmentId, int.Parse(item.ScheduledTask.Data), item.ScheduledTask.Note, autoGenerated: true);
					}
					else if (item.ScheduledTask.TaskType == (int)TaskTypes.DepartmentStaffingReset)
					{
						// The stored target is a meaning ("b{n}") or a level saved before meanings; either way it becomes the
						// department's own staffing level (custom or built-in) when the reset runs.
						var staffing = await customStateService.ResolveStaffingResetAsync(item.ScheduledTask.DepartmentId, item.ScheduledTask.Data);

						if (staffing.HasValue)
						{
							// Active members only (hidden members are left alone, like every other sweep); one failure doesn't stop the rest.
							var users = await departmentsService.GetAllUsersForDepartment(item.ScheduledTask.DepartmentId, false);

							foreach (var user in users)
							{
								try
								{
									await userStateService.CreateUserState(user.UserId, item.ScheduledTask.DepartmentId, staffing.Value, $"Department Staffing Reset {item.ScheduledTask.ScheduledTaskId}", autoGenerated: true);
								}
								catch (Exception ex)
								{
									Logging.LogException(ex, $"Department Staffing Reset {item.ScheduledTask.ScheduledTaskId}: user {user.UserId}");
								}
							}
						}
						else
						{
							Logging.LogError($"Department Staffing Reset {item.ScheduledTask.ScheduledTaskId}: '{item.ScheduledTask.Data}' matches none of department {item.ScheduledTask.DepartmentId}'s staffing levels; nobody was reset.");
						}
					}
				}
				catch (Exception ex)
				{
					Logging.LogException(ex);
					success = false;
					result = ex.ToString();
				}

				if (success)
					await scheduledTasksService.CreateScheduleTaskLogAsync(item.ScheduledTask);
			}

			return new Tuple<bool, string>(success, result);
		}
	}
}
